# Solicitar el número de horas trabajadas y el costo por hora
horas = int(input("Ingrese el número de horas trabajadas: "))
costo_por_hora = float(input("Ingrese el costo por hora: "))

# Calcular el pago total
pago_total = horas * costo_por_hora

# Mostrar el resultado
print(f"El pago que le corresponde es: ${pago_total}")

